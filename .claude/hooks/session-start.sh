#!/bin/bash
#
# САМОЛЕЧЕНИЕ РАБОЧЕЙ КОПИИ ПОСЛЕ ПЕРЕРАБОТКИ КОНТЕЙНЕРА.
#
# Облачная сессия останавливается после простоя, и её виртуальная машина утилизируется. При
# возвращении поднимается НОВАЯ машина из снимка файловой системы окружения, а в этом снимке лежит
# клон репозитория, сделанный когда-то давно. История разговора восстанавливается, рабочая копия —
# нет: она откатывается на тот старый коммит, причём с чистым деревом и правдоподобным видом.
#
# Ровно это и происходило: за одну сессию трижды, каждый раз откатывая репозиторий на v22.5.1 при
# выпущенной v24.19.0. Поймать такое глазом почти нельзя — файлы на месте, git не жалуется.
#
# ПОЧЕМУ ХУК, А НЕ SETUP-СКРИПТ ОКРУЖЕНИЯ. Setup-скрипт выполняется только при ПЕРВОМ запуске сессии
# в окружении, а его результат кладётся в тот самый снимок; при возобновлении он не запускается
# вовсе. SessionStart-хук запускается при каждом старте, включая возобновлённый, — то есть именно
# тогда, когда беда и случается.
#
# ЧЕГО ЭТОТ ХУК НЕ МОЖЕТ В ПРИНЦИПЕ, и это выяснилось 2026-09-02 на четвёртом откате за сессию.
# Снимок ФС окружения сделан на v22.5.1 (коммит 69e9d08, 21 августа), а каталога `.claude` в том
# коммите НЕТ ВОВСЕ: хук появился позже. Значит откат сносит и сам хук — и лечить откат становится
# НЕКОМУ. Курица и яйцо: защита живёт внутри того, что она защищает.
#
# Поэтому та же работа продублирована ВНЕ репозитория, где отката нет:
#   /root/.claude/hooks/stl-heal.sh    — то же самое лечение на SessionStart;
#   /root/.claude/hooks/stl-guard.sh   — сторож на PreToolUse(Bash): откаты случаются ПОСРЕДИ ХОДА,
#                                        когда SessionStart не бывает вовсе, и оба хука выше молчат.
#   /root/.claude/settings.json        — их регистрация.
# Файлы эти НЕ под контролем версий (в том и смысл), поэтому здесь записано, что они есть и зачем:
# иначе следующий, кто это читает, будет чинить уже починенное.
#
# ЧЕГО ЭТОТ ХУК НЕ ДЕЛАЕТ, и это важнее того, что делает:
#   * не трогает ГРЯЗНОЕ дерево — незакоммиченная работа неприкосновенна, даже ценой отката;
#   * не трогает отсоединённый HEAD;
#   * перематывает ТОЛЬКО ВПЕРЁД: локальный коммит обязан быть предком удалённого. Разошлись или
#     локальная ветка впереди — не трогает ничего;
#   * никогда не делает reset --hard, не удаляет файлов и не переключает ветку на чужую: цель одна —
#     догнать origin ТОЙ ЖЕ ветки;
#   * всегда завершается нулём: сорванный хук не имеет права мешать сессии начаться.
#
set -uo pipefail

cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

# Беда сугубо облачная. Локально молчим: неожиданный checkout под руками у человека — это хуже
# отката, который он и так увидит.
[ "${CLAUDE_CODE_REMOTE:-}" = "true" ] || exit 0

if [ -n "$(git status --porcelain 2>/dev/null)" ]; then
  echo "session-start: дерево не чистое — не трогаю (незакоммиченное дороже)"
  exit 0
fi

branch="$(git symbolic-ref --quiet --short HEAD 2>/dev/null)"
if [ -z "$branch" ]; then
  echo "session-start: HEAD отсоединён — не трогаю"
  exit 0
fi

if ! git fetch --quiet origin "$branch" 2>/dev/null; then
  echo "session-start: origin/$branch недоступен — оставляю как есть"
  exit 0
fi

here="$(git rev-parse HEAD 2>/dev/null)"
there="$(git rev-parse FETCH_HEAD 2>/dev/null)"
[ -n "$here" ] && [ -n "$there" ] || exit 0

if [ "$here" = "$there" ]; then
  echo "session-start: $branch на уровне origin (${here:0:7})"
  exit 0
fi

if git merge-base --is-ancestor "$here" "$there" 2>/dev/null; then
  if git checkout --quiet -B "$branch" "$there" 2>/dev/null; then
    echo "session-start: $branch перемотана ${here:0:7} → ${there:0:7} — контейнер вернулся из снимка"
  else
    echo "session-start: перемотать $branch не удалось — оставляю ${here:0:7}"
  fi
else
  echo "session-start: локальная $branch не предок origin/$branch — не трогаю (${here:0:7})"
fi
# Отметка для сторожа. Живёт ВНЕ репозитория: внутри её снесло бы тем же откатом.
git rev-parse HEAD > /root/.claude/stl-head-stamp 2>/dev/null || true
exit 0
