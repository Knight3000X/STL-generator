#!/bin/bash
# СТОРОЖ ПОСРЕДИ ХОДА. Откаты случаются не на старте сессии, а между вызовами инструментов — за одну
# сессию их было четыре, и дважды я работал по откаченному дереву, не заметив этого.
#
# ЧЕГО СТОРОЖ НЕ ДЕЛАЕТ: он НЕ ЛЕЧИТ и НЕ БЛОКИРУЕТ. Молча выдернуть файлы посреди правки — хуже
# самого отката, поэтому он только КРИЧИТ, а чинит человек (или я) осознанно. Выходит всегда нулём.
#
# Дешевизна обязательна: он идёт перед КАЖДЫМ вызовом Bash. Обычный путь — один git rev-parse
# (миллисекунды) и сравнение строк. Сеть не трогается вовсе.
set -uo pipefail
R=/home/user/STL-generator
S=/root/.claude/stl-head-stamp
[ -f "$S" ] || exit 0
here="$(git -C "$R" rev-parse HEAD 2>/dev/null)" || exit 0
want="$(cat "$S" 2>/dev/null)"
[ -n "$here" ] && [ -n "$want" ] || exit 0
[ "$here" = "$want" ] && exit 0
# Разошлись. Вперёд ушли — это нормальная работа, отметку двигаем.
if git -C "$R" merge-base --is-ancestor "$want" "$here" 2>/dev/null; then
  echo "$here" > "$S"; exit 0
fi
# Назад — это откат контейнера.
v="$(grep -o "APP_VERSION = '[^']*'" "$R/parametric-stl-generator.html" 2>/dev/null | head -1)"
echo "ВНИМАНИЕ: рабочая копия УЕХАЛА НАЗАД — ${want:0:7} → ${here:0:7} ($v)." >&2
echo "Это откат контейнера из снимка, а не ваша правка. Всё, что сделано после ${want:0:7}, в дереве ОТСУТСТВУЕТ." >&2
echo "Лечится: git -C $R fetch origin <ветка> && git -C $R checkout -B <ветка> origin/<ветка>" >&2
echo "(или запустите /root/.claude/hooks/stl-heal.sh)" >&2
exit 0
