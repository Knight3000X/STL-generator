// РАСХОД И ВРЕМЯ — ПО ОБОЛОЧКЕ И ЗАПОЛНЕНИЮ, А НЕ ПО ЛИТОМУ ОБЪЁМУ.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ. До v25.44.0 вес и время брались из объёма сетки, то есть считали деталь ЛИТОЙ.
// Для стенки 1.6 мм это верно, а для куба 40×40×40 при 15 % заполнения — нет: он весит около
// двадцати граммов, а приложение объявляло семьдесят девять. Число не отзывалось ни на одну ручку
// печати, и читалось при этом как измеренное — самый опасный сорт вранья.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ. Не «оценка правдоподобна» (правдоподобие не проверишь), а ТОЖДЕСТВА,
// которые обязаны держаться при любых ручках:
//   • при 100 % заполнения расход равен литому объёму — ровно, а не примерно;
//   • оболочка никогда не больше самой детали;
//   • у полой детали, чья стенка тоньше оболочки, печатается ВСЯ деталь;
//   • каждая ручка двигает число в свою сторону и ни одна не двигает геометрию;
//   • куб 40³ считается ВРУЧНУЮ и сходится до кубического миллиметра.
//
// Run: ./run-all.sh

let pass = 0, fail = 0;
function chk(n, c, e){ if (c){ pass++; console.log('  OK  ', n); }
  else { fail++; console.log('  FAIL', n, e !== undefined ? JSON.stringify(e) : ''); } }
const near = (a, b, eps) => Math.abs(a - b) < (eps === undefined ? 1e-6 : eps);

const P = ov => { logos.length = 0; boxHoles.length = 0;
  if (typeof dieFaces !== 'undefined') dieFaces.length = 0;
  Object.assign(paramState.box, defaultBoxParams(), {gfBaseplate:false}, ov); return paramState.box; };
const budgetOf = ov => { const p = P(ov); return printBudget(buildTrisForShape('box', p), p); };

console.log('=== куб 40×40×40: расход считается вручную и сходится ===');
{
  /* САМЫЙ ПРОСТОЙ СЛУЧАЙ, И ПОТОМУ САМЫЙ СТРОГИЙ. У куба 40³ шесть граней по 1600 мм²: две
     горизонтальные (пол и потолок) и четыре боковые. Толщина крышки — 4 слоя по 0.2 = 0.8 мм,
     оболочки по стенке — 3 периметра по 0.4 = 1.2 мм. Оболочка = 2·1600·0.8 + 4·1600·1.2 = 10240 мм³.
     Внутри остаётся 64000 − 10240 = 53760, из них 15 % = 8064. Итого 18304 мм³. */
  const p = P({});
  const b = printBudget(buildTrisForShape('box', p), p);
  chk('литой объём — 64000 мм³', near(b.solid, 64000, 1e-6), b.solid);
  chk('оболочка — 10240 мм³ (2·1600·0.8 + 4·1600·1.2)', near(b.skin, 10240, 1e-6), b.skin);
  chk('заполнение — 8064 мм³ (15 % от остатка)', near(b.infill, 8064, 1e-6), b.infill);
  chk('материала — 18304 мм³', near(b.mat, 18304, 1e-6), b.mat);
  chk('  то есть 29 % литого', Math.round(b.fill*100) === 29, b.fill);
  /* Вес — объём на плотность, и плотность берётся у ТАБЛИЦЫ, а не пишется здесь заново. */
  chk('вес — материал на плотность выбранного материала',
      near(b.mass, 18304/1000*FIL_MAT.pla.g, 1e-9), {вес:b.mass, плотность:FIL_MAT.pla.g});
  chk('и литой вес назван отдельно', near(b.massSolid, 64000/1000*FIL_MAT.pla.g, 1e-9), b.massSolid);
  /* Филамент — тот же объём, но нитью Ø1.75: площадь сечения 2.4053 мм². */
  chk('филамент — тот же объём нитью Ø1.75',
      near(b.filamentMm, 18304/(Math.PI*0.875*0.875), 1e-6), b.filamentMm);
  chk('  это около 7.6 метра', Math.abs(b.filamentMm/1000 - 7.61) < 0.05, b.filamentMm/1000);
}

console.log('\n=== тождества: то, что обязано держаться при любых ручках ===');
{
  /* СТО ПРОЦЕНТОВ ЗАПОЛНЕНИЯ — ЭТО РОВНО ЛИТАЯ ДЕТАЛЬ. Не «примерно»: оболочка зажата самой
     деталью, а остаток умножается на единицу, и сумма обязана дать объём сетки в точности.
     Разойдись это — и вся оценка потеряла бы точку отсчёта. */
  /* ЛОТОК ЗАДАЁТСЯ ТАК, КАК ЕГО ЗАДАЁТ ПАНЕЛЬ — `hollow` + `cavityDepth`, а не внутренним `rim`.
     Первая редакция ставила `rim:true` напрямую и этим ПОРТИЛА ВСЕ СЛЕДУЮЩИЕ НАБОРЫ: строки панели
     у `rim` нет вовсе (он живёт только внутри `normalizeBoxParams`), а значит `defaultBoxParams()`
     его не перезаписывает — и куб из следующей проверки оказывался лотком в семь тысяч
     треугольников. Приложение так не делает: панель пишет `cavityDepth`, а `rim` появляется лишь в
     КОПИИ параметров внутри правила. Проверять надо то, что человек может получить. */
  const CASES = [['куб', {}], ['полый', {hollow:true}], ['лоток', {hollow:true, cavityDepth:8}],
                 ['шестерня', {gearMode:'spur'}], ['резьба', {threadMode:'bolt'}],
                 ['крючок', {hookMount:'wall'}], ['лист', {sheetShape:'rect'}],
                 ['кейкап', {keycapMode:'single'}], ['корпус', {pbPart:'tray'}]];
  for (const [nm, ov] of CASES){
    const full = budgetOf(Object.assign({prtInfill:100}, ov));
    chk(nm + ': при 100 % заполнения расход равен литому объёму',
        full && near(full.mat, full.solid, Math.max(1e-6, full.solid*1e-12)), full && {mat:full.mat, solid:full.solid});
  }
  for (const [nm, ov] of CASES){
    const b = budgetOf(ov);
    chk(nm + ': оболочка не больше самой детали', b && b.skin <= b.solid + 1e-9, b && {skin:b.skin, solid:b.solid});
    chk(nm + ':   и материала не больше литого', b && b.mat <= b.solid + 1e-9, b && {mat:b.mat, solid:b.solid});
    chk(nm + ':   и не меньше оболочки', b && b.mat >= b.skin - 1e-9, b && {mat:b.mat, skin:b.skin});
  }
  /* ТОНКАЯ СТЕНКА ПЕЧАТАЕТСЯ ЦЕЛИКОМ. У полого ящика со стенкой 2 мм оболочка (3 периметра = 1.2 мм
     с каждой стороны) толще самой стенки, и слайсер кладёт её сплошняком. Заполнение при этом не
     решает ничего — и число обязано это показывать, иначе человек будет крутить ручку впустую. */
  const thin15 = budgetOf({hollow:true, wallThickness:2, prtInfill:15});
  const thin80 = budgetOf({hollow:true, wallThickness:2, prtInfill:80});
  chk('тонкая стенка печатается целиком — доля ровно единица', near(thin15.fill, 1, 1e-9), thin15.fill);
  chk('  и заполнение на ней ничего не меняет', near(thin15.mat, thin80.mat, 1e-9),
      {'15%':thin15.mat, '80%':thin80.mat});
}

console.log('\n=== каждая ручка двигает число в свою сторону ===');
{
  const base = budgetOf({});
  chk('больше заполнения — больше материала', budgetOf({prtInfill:50}).mat > base.mat);
  chk('меньше заполнения — меньше',           budgetOf({prtInfill:0}).mat < base.mat);
  chk('больше периметров — больше',           budgetOf({prtWalls:6}).mat > base.mat);
  chk('больше сплошных слоёв — больше',       budgetOf({prtSolid:10}).mat > base.mat);
  chk('нулевое заполнение и ноль слоёв — только периметры',
      budgetOf({prtInfill:0, prtSolid:0}).mat < budgetOf({prtInfill:0}).mat);
  /* ВЫСОТА СЛОЯ ДВИГАЕТ КРЫШКУ, А НЕ СТЕНКУ: сплошные слои считаются слоями, периметры — проходами. */
  chk('толще слой — толще крышка, значит больше материала',
      budgetOf({printLayerH:0.3}).mat > budgetOf({printLayerH:0.1}).mat);
  /* СОПЛО ДВИГАЕТ ОБА ЧИСЛА, И В РАЗНЫЕ СТОРОНЫ: оболочка толще, а времени меньше — подача растёт
     как площадь сечения прохода. Ровно это и есть довод за крупное сопло, и число обязано его знать. */
  const n04 = budgetOf({}), n08 = budgetOf({printNozzle:'0.8'});
  chk('крупное сопло: материала больше', n08.mat > n04.mat, {'0.4':n04.mat, '0.8':n08.mat});
  chk('  а времени меньше', n08.hours < n04.hours, {'0.4':n04.hours, '0.8':n08.hours});
  chk('  и подача растёт как КВАДРАТ сопла, а не как сопло',
      near(n08.mat/n08.hours / (n04.mat/n04.hours), 4, 1e-9), n08.mat/n08.hours / (n04.mat/n04.hours));
  /* МАТЕРИАЛ ДВИГАЕТ ВЕС, НО НЕ ОБЪЁМ: плотность — свойство нити, а не геометрии. Компенсация
     усадки при этом ВЫКЛЮЧЕНА нарочно: она — свойство геометрии, и с нею ABS-деталь строится на
     полпроцента крупнее, то есть объём честно другой. Первая редакция этого не учла и объявила
     расхождением ровно то, что приложение делает правильно. */
  const pla = budgetOf({matShrink:false}), abs = budgetOf({matShrink:false, printMat:'abs'});
  chk('другой материал: объём тот же', near(pla.mat, abs.mat, 1e-9));
  chk('  а вес другой', abs.mass < pla.mass, {pla:pla.mass, abs:abs.mass});
  chk('  и ровно по таблице плотностей',
      near(abs.mass/pla.mass, FIL_MAT.abs.g/FIL_MAT.pla.g, 1e-9));
}

console.log('\n=== ни одна из трёх ручек не двигает ГЕОМЕТРИЮ ===');
{
  /* РУЧКИ РАСХОДА — НЕ РУЧКИ ФОРМЫ. Они меняют только оценку; сетка от них обязана остаться той же
     до треугольника. Без этой проверки «заполнение» однажды поехало бы в построитель. */
  const hash = t => { let h = 0x811c9dc5;
    const s = t.map(T => T.map(v => v.map(x => Math.abs(x) < 5e-7 ? 0 : +x.toFixed(6)).join(',')).join(';')).join('|');
    for (let i = 0; i < s.length; i++) h = (h ^ s.charCodeAt(i)) * 16777619 >>> 0;
    return h.toString(16) + '-' + s.length; };
  const BASE = hash(buildTrisForShape('box', P({})));
  for (const ov of [{prtWalls:1}, {prtWalls:8}, {prtSolid:0}, {prtSolid:12}, {prtInfill:0}, {prtInfill:100}])
    chk('сетка не изменилась от ' + JSON.stringify(ov), hash(buildTrisForShape('box', P(ov))) === BASE);
}

console.log('\n=== оценка отказывается, когда мерить нечего ===');
{
  chk('без сетки — нет ответа', printBudget(null, P({})) === null);
  chk('пустая сетка — нет ответа', printBudget([], P({})) === null);
  /* ВЫРОЖДЕННАЯ СЕТКА ТОЖЕ НЕ ОТВЕТ: три точки на одной прямой имеют нулевой объём, и делить на
     него значило бы выдать бесконечную долю вместо честного «не знаю». */
  chk('вырожденная сетка — нет ответа',
      printBudget([[[0,0,0],[1,0,0],[2,0,0]]], P({})) === null);
}

console.log('\n=== разбор площади по направлению грани ===');
{
  /* ПЛОЩАДЬ ДЕЛИТСЯ ТЕМ ЖЕ ПОРОГОМ, ЧТО И НАВИСАНИЯ: 45°. Куб даёт ровно треть площади плоской
     (две грани из шести) и две трети боковой. */
  const t = buildTrisForShape('box', P({}));
  const A = meshAreaSplit(t);
  chk('и это правда куб из двенадцати треугольников', t.length === 12, t.length);
  chk('у куба площадь 9600 мм²', near(A.total, 9600, 1e-6), A.total);
  chk('  из них плоской — треть', near(A.flat, 3200, 1e-6), A.flat);
  chk('  и боковой — две трети', near(A.side, 6400, 1e-6), A.side);
  chk('  и сумма сходится', near(A.flat + A.side, A.total, 1e-9));
  /* НАКЛОННАЯ ГРАНЬ КРУЧЕ 45° СЧИТАЕТСЯ БОКОВОЙ — иначе конус получил бы крышку там, где её нет. */
  const steep = meshAreaSplit([[[0,0,0],[10,0,0],[0,10,0.1]]]);
  chk('почти вертикальная грань — боковая', steep.side > 0 && steep.flat === 0, steep);
  const flat = meshAreaSplit([[[0,0,0],[10,0,0],[0,0,10]]]);
  chk('горизонтальная — плоская', flat.flat > 0 && flat.side === 0, flat);
}

console.log('\n=== TOTAL:', pass, 'passed,', fail, 'failed ===');
if (fail) process.exitCode = 1;
