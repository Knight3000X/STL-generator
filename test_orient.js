// ОРИЕНТАЦИЯ И ПЕРВЫЙ СЛОЙ — ДВА ВОПРОСА, НА КОТОРЫЕ ПРИЛОЖЕНИЕ ЗНАЛО ОТВЕТ И МОЛЧАЛО.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ. «Авто-ориентация» была кнопкой: она молча поворачивала деталь, и пока её не
// нажали, приложение не говорило ничего — «нависаний 12 см²», а что с ними делать, знай сам. А про
// то, ЧЕМ деталь стоит на столе, оно не говорило вовсе: башенка сечением с ноготь и высотой в ладонь
// отрывается на первом же рывке головы, и узнаётся это на четвёртом часу печати.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ. Главное — что БЫСТРЫЙ ПУТЬ РАВЕН ЧЕСТНОМУ: перебор шести положений считает
// направления, а не вертит сетку, и обязан дать ровно то же, что настоящий поворот всей детали.
// Дальше — что совет даётся только когда он что-то меняет, что пятно первого слоя считается по
// граням на столе (а не по габариту), и что опрокидывание меряется от ЦЕНТРА МАСС.
//
// Run: ./run-all.sh

let pass = 0, fail = 0;
function chk(n, c, e){ if (c){ pass++; console.log('  OK  ', n); }
  else { fail++; console.log('  FAIL', n, e !== undefined ? JSON.stringify(e) : ''); } }
const near = (a, b, eps) => Math.abs(a - b) < (eps === undefined ? 1e-6 : eps);

const P = ov => { logos.length = 0; boxHoles.length = 0;
  if (typeof dieFaces !== 'undefined') dieFaces.length = 0;
  Object.assign(paramState.box, defaultBoxParams(), {gfBaseplate:false}, ov); return paramState.box; };

console.log('=== быстрый путь равен честному повороту ===');
{
  /* САМАЯ ВАЖНАЯ ПРОВЕРКА ФАЙЛА. Перебор не вертит сетку — он считает нависание ВДОЛЬ НАПРАВЛЕНИЯ,
     и направление это берётся у самого `rotateTris` (три единичных вектора прогоняются через него
     же). Ошибиться в соглашении о порядке и знаках поворота легче лёгкого, и ошибка была бы тихой:
     совет «поверните на 90° по X» увёл бы деталь не туда, а число рядом осталось бы красивым.
     Поэтому здесь сравнивается с ЧЕСТНЫМ путём — поворотом всей сетки и замером сверху. */
  const SHAPES = [['куб', {}], ['крючок', {hookMount:'wall'}], ['уголок', {mntMode:'lbracket'}],
                  ['воронка', {fnOn:true}], ['коническая пара', {gearMode:'bevel'}],
                  ['подставка', {psOn:true}], ['футляр', {pipMode:'box'}]];
  for (const [nm, ov] of SHAPES){
    const t = buildTrisForShape('box', P(ov));
    const s = orientationSpec(t);
    let worst = 0, where = null;
    for (const o of s.list){
      const honest = overhangArea(rotateTris(t, o.rx, 0, o.rz));
      const d = Math.abs(honest - o.overhang);
      if (d > worst){ worst = d; where = {положение:o.t, честно:honest, быстро:o.overhang}; }
    }
    chk(nm + ': все шесть положений совпали с честным поворотом', worst < 1e-6, where);
  }
}

console.log('\n=== перебор считает то, что обещает ===');
{
  const t = buildTrisForShape('box', P({}));
  const s = orientationSpec(t);
  chk('положений ровно шесть', s.list.length === 6, s.list.length);
  chk('первое из них — «как есть» (rx=0, rz=0)', s.list[0].rx === 0 && s.list[0].rz === 0);
  chk('и оно же объявлено текущим', s.cur === s.list[0]);
  chk('лучшее — с наименьшим нависанием',
      s.list.every(o => o.overhang >= s.best.overhang - 1), {лучшее:s.best.overhang, все:s.list.map(o => o.overhang)});
  /* У КУБА ВСЕ ШЕСТЬ ОДИНАКОВЫ — нависаний нет ни в одном. Ничья обязана достаться «как есть»:
     поворачивать деталь без причины — это не совет. */
  chk('у куба нависаний нет ни в одном положении', s.list.every(o => o.overhang < 1e-9));
  chk('  и ничья достаётся «как есть»', s.best === s.cur);
  chk('  а совета нет', s.worth === false);
  /* ВЫСОТА И ПЯТНО — ПЕРЕСТАНОВКА ГАБАРИТА, и у куба они равны при любом положении. */
  chk('высота у куба одна во всех положениях', s.list.every(o => near(o.height, 40)), s.list.map(o => o.height));
}

console.log('\n=== клин: положение решает, и ответ известен заранее ===');
{
  /* РУЧНАЯ ФИГУРА С ИЗВЕСТНЫМ ОТВЕТОМ. Треугольная призма: основание 20 по X, подъём 5 по Y,
     глубина 10 по Z. Как есть — наклонная грань смотрит ВВЕРХ, нависаний нет вовсе. Вверх ногами
     она смотрит вниз под 14° к горизонту, то есть круче 45° к вертикали, и нависает ВСЯ: её площадь
     ровно 10·√(20² + 5²) = 10·√425 ≈ 206.16 мм². Никакой построитель тут не участвует — числа
     проверяются против самой геометрии. */
  const A=[0,0,0], B=[20,0,0], C=[0,5,0], A2=[0,0,10], B2=[20,0,10], C2=[0,5,10];
  const wedge = [
    [A,C,B], [A2,B2,C2],                       // торцы: ±Z
    [A,B,B2], [A,B2,A2],                       // низ (y=0)
    [A,A2,C2], [A,C2,C],                       // задняя стенка (x=0)
    [B,C,C2], [B,C2,B2],                       // наклонная
  ];
  chk('клин замкнут и объём положителен', meshVolume(wedge) > 0 && near(meshVolume(wedge), 500, 1e-6), meshVolume(wedge));
  const s = orientationSpec(wedge);
  const asIs = s.list.find(o => o.rx === 0 && o.rz === 0);
  const flip = s.list.find(o => o.rx === 180 && o.rz === 0);
  chk('как есть — нависаний нет', near(asIs.overhang, 0, 1e-9), asIs.overhang);
  chk('вверх ногами — нависает вся наклонная грань (10·√425)',
      near(flip.overhang, 10*Math.sqrt(425), 1e-6), {получено:flip.overhang, ждали:10*Math.sqrt(425)});
  chk('  и лучшим объявлено не «вверх ногами»', s.best !== flip, s.best.t);
  /* И ВЫСОТА МЕНЯЕТСЯ ВМЕСТЕ С ПОЛОЖЕНИЕМ: на боку клин выше, чем лёжа. */
  const side = s.list.find(o => o.rz === 90);
  chk('на боку высота — 20 (бывшая длина)', near(side.height, 20), side.height);
  chk('  а лёжа — 5', near(asIs.height, 5), asIs.height);
}

console.log('\n=== подпись положения — следствие поворота, а не память ===');
{
  /* ПОДПИСИ Я ПЕРЕПУТАЛ С ПЕРВОГО РАЗА — у поворотов вокруг Z, — и числа при этом остались верными:
     кнопка вертела куда надо, а строка называла другую сторону. Такое не ловится ни одним замером
     площади; поймала это мутация «знак поворота перепутан», которая ПЕРЕЖИЛА первую редакцию файла.
     Теперь подпись сверяется с геометрией: какая грань уходит вниз — считается, а не помнится. */
  chk('вниз уходит именно та грань, что названа в подписи',
      ORIENT_CANDIDATES.every(c => {
        const f = orientDownFace(c.rx, c.rz);
        return c.rx === 0 && c.rz === 0 ? f === '-Y'
             : c.t.indexOf(ORIENT_DOWN_NAME[f]) >= 0 || (f === '+Y' && c.t === 'вверх ногами'); }),
      ORIENT_CANDIDATES.map(c => ({подпись:c.t, вниз:orientDownFace(c.rx, c.rz)})));
  /* И ЧТО САМА ЭТА МАШИНКА РАБОТАЕТ: у каждого положения ровно одна нижняя грань, и все шесть разные. */
  const downs = ORIENT_CANDIDATES.map(c => orientDownFace(c.rx, c.rz));
  chk('  у каждого положения своя нижняя грань', new Set(downs).size === 6 && downs.every(Boolean), downs);
  chk('  и «как есть» кладёт вниз низ', orientDownFace(0, 0) === '-Y');
  chk('  а «вверх ногами» — верх', orientDownFace(180, 0) === '+Y');
  chk('  поворот вокруг Z на +90° кладёт вниз ЛЕВУЮ', orientDownFace(0, 90) === '-X');
  chk('  а на −90° — правую', orientDownFace(0, -90) === '+X');
}

console.log('\n=== совет даётся, только когда он что-то меняет ===');
{
  /* ПОРОГ НАЗВАН ЧИСЛОМ, А НЕ НАСТРОЕНИЕМ: выигрыш должен быть и заметным по площади (больше
     квадратного сантиметра), и заметным по доле (треть). Поворот ради пяти процентов — это шум:
     человек его выполнит, ничего не заметит и перестанет верить следующему совету. */
  const t = buildTrisForShape('box', P({mntMode:'lbracket'}));
  const s = orientationSpec(t);
  chk('у уголка совет есть', s.worth === true, {сейчас:s.cur.overhang, лучшее:s.best.overhang});
  chk('  и он выигрывает больше трети', s.cur.overhang - s.best.overhang > s.cur.overhang*0.3);
  chk('  и больше квадратного сантиметра', s.cur.overhang - s.best.overhang > 100);
  chk('у куба совета нет', orientationSpec(buildTrisForShape('box', P({}))).worth === false);
  /* САМО ПРАВИЛО «стоит ли советовать» — отдельным именем, и проверяется оно ЧИСЛАМИ, а не поиском
     подходящей детали. Пока оно было выражением внутри перебора, мутация «советовать всегда»
     проходила молча: у куба лучшее и текущее совпадают, и разницы не видно ни на одной форме. */
  chk('выигрыш втрое — советовать', orientWorth(1000, 300) === true);
  chk('выигрыш в пять процентов — не советовать', orientWorth(1000, 950) === false);
  chk('выигрыш меньше квадратного сантиметра — не советовать', orientWorth(120, 30) === false);
  chk('выигрыша нет вовсе — не советовать', orientWorth(500, 500) === false);
  chk('стало хуже — тем более не советовать', orientWorth(300, 900) === false);
  /* КНОПКА СПРАШИВАЕТ ТО ЖЕ ПРАВИЛО — иначе она поворачивала бы не туда, куда советует строка. */
  const b = bestOrientation(t);
  chk('кнопка и совет — одно правило', b.rx === s.best.rx && b.rz === s.best.rz && near(b.area, s.best.overhang),
      {кнопка:b, совет:{rx:s.best.rx, rz:s.best.rz, area:s.best.overhang}});
}

console.log('\n=== пятно первого слоя: по граням на столе, а не по габариту ===');
{
  const p = P({});
  const g = bedGripSpec(buildTrisForShape('box', p), p);
  chk('у куба 40³ пятно ровно 1600 мм²', near(g.area, 1600), g.area);
  chk('  высота — 40', near(g.height, 40), g.height);
  chk('  запас до края — 20 (центр масс в середине)', near(g.margin, 20), g.margin);
  chk('  стройность — единица', near(g.slender, 1), g.slender);
  const tile = P({width:100, height:2, depth:100});
  chk('у плитки 100×2×100 пятно 10000 мм²', near(bedGripSpec(buildTrisForShape('box', tile), tile).area, 10000));
  const tower = P({width:8, height:80, depth:8});
  const gt = bedGripSpec(buildTrisForShape('box', tower), tower);
  chk('у башенки 8×80×8 пятно 64 мм²', near(gt.area, 64), gt.area);
  chk('  и стройность 10:1', near(gt.slender, 10), gt.slender);
  /* СТРОЙНОСТЬ МЕРЯЕТСЯ ПО УЗКОЙ СТОРОНЕ ПЯТНА, а не по широкой: падает деталь через узкую. У
     квадратной подошвы разницы нет вовсе — потому первая редакция и не заметила подмены, а мутация
     «мерить по большей стороне» её пережила. Здесь подошва НЕквадратная, и стороны говорят разное. */
  const fin = P({width:8, height:80, depth:40});
  const gf = bedGripSpec(buildTrisForShape('box', fin), fin);
  chk('у пластины 8×80×40 пятно 320 мм²', near(gf.area, 320), gf.area);
  chk('  стройность считается по узкой стороне: 80/8 = 10', near(gf.slender, 10), gf.slender);
  chk('  а не по широкой (было бы 2)', !near(gf.slender, 2));
  /* ГРАНИ, СМОТРЯЩИЕ ВВЕРХ, В ПЯТНО НЕ ВХОДЯТ — даже когда лежат на самом столе. Так бывает у сеток
     с совпадающими гранями: снизу лист, сверху лист, оба на нуле. Считать их обе значило бы удвоить
     пятно там, где детали не прибавилось. */
  const sheet = [[[0,0,0],[10,0,0],[0,0,10]], [[0,0,0],[0,0,10],[10,0,0]]];   // одна вниз, одна вверх
  const gsh = bedGripSpec(sheet, P({}));
  chk('совпадающая грань «вверх» в пятно не идёт', near(gsh.area, 50), gsh.area);
  /* ГАБАРИТ — НЕ ПЯТНО. У ажурного шара габарит под сотню миллиметров, а стоит он несколькими
     пятнышками: мера обязана показывать именно их, иначе она отвечает не на тот вопрос. */
  const ball = P({lnMode:'ball'});
  const gb = bedGripSpec(buildTrisForShape('box', ball), ball);
  const bb = bboxOfTris(buildTrisForShape('box', ball));
  chk('у шара пятно много меньше габаритного квадрата',
      gb.area < (bb.hi[0]-bb.lo[0])*(bb.hi[2]-bb.lo[2])*0.25,
      {пятно:gb.area, габарит:(bb.hi[0]-bb.lo[0])*(bb.hi[2]-bb.lo[2])});
}

console.log('\n=== опрокидывание меряется от центра масс ===');
{
  /* Г-ОБРАЗНАЯ ФИГУРА РУКАМИ: тонкая высокая стойка и широкая тяжёлая полка НАВЕРХУ, сдвинутая
     вбок. Середина габарита у неё в одном месте, а центр масс — в другом, и опрокидывается она
     туда, где тяжело. Мера, считающая от габарита, этого не увидит. */
  const box = (x0,y0,z0,x1,y1,z1) => {
    const v = [[x0,y0,z0],[x1,y0,z0],[x1,y1,z0],[x0,y1,z0],[x0,y0,z1],[x1,y0,z1],[x1,y1,z1],[x0,y1,z1]];
    const q = (a,b,c,d) => [[v[a],v[b],v[c]],[v[a],v[c],v[d]]];
    return [].concat(q(0,3,2,1), q(4,5,6,7), q(0,1,5,4), q(1,2,6,5), q(2,3,7,6), q(3,0,4,7));
  };
  const post  = box(0, 0, 0, 6, 40, 6);          // стойка 6×40×6 у начала координат
  const shelf = box(0, 40, 0, 60, 46, 6);        // полка 60×6×6 наверху, свисает вбок
  const ell = post.concat(shelf);
  const g = bedGripSpec(ell, P({}));
  chk('пятно — только подошва стойки (36 мм²)', near(g.area, 36), g.area);
  chk('центр масс ушёл вбок от стойки', g.com[0] > 6, g.com && g.com[0]);
  chk('  и запас отрицателен: деталь опрокинется', g.margin < 0, g.margin);
  /* А ТА ЖЕ ПОЛКА СНИЗУ СТОИТ: центр масс над опорой, запас положителен. И ЗАПАС ЭТОТ СЧИТАЕТСЯ
     ЧИСЛОМ, а не «больше нуля»: основание 60×40×6 (объём 14400, центр по X — 30) и стойка 6×40×40
     (объём 9600, центр по X — 3) дают центр масс на (14400·30 + 9600·3)/24000 = 19.2, а пятно
     тянется от 0 до 60. Запас по X — 19.2; по Z обе коробки от 0 до 40, центр 20, запас 20. Меньший
     из них и есть ответ: 19.2. Считай мера от СЕРЕДИНЫ ГАБАРИТА — вышло бы ровно 20, и разница
     видна только на такой, несимметричной детали. Мутация «считать от середины» пережила первую
     редакцию именно потому, что там деталь была симметричной по X. */
  const stable = box(0, 0, 0, 60, 6, 40).concat(box(0, 6, 0, 6, 46, 40));
  const gs = bedGripSpec(stable, P({}));
  chk('перевёрнутая — стоит: запас положителен', gs.margin > 0, gs.margin);
  chk('  и центр масс сдвинут к тяжёлому основанию: 19.2', near(gs.com[0], 19.2, 1e-9), gs.com[0]);
  chk('  запас до края — ровно 19.2, а не 20 от середины габарита', near(gs.margin, 19.2, 1e-9), gs.margin);
}

console.log('\n=== обе меры отказываются, когда мерить нечего ===');
{
  chk('перебор без сетки — нет ответа', orientationSpec(null) === null && orientationSpec([]) === null);
  chk('пятно без сетки — нет ответа', bedGripSpec(null, P({})) === null && bedGripSpec([], P({})) === null);
  /* ДЕТАЛЬ БЕЗ ПЛОСКОЙ ПОДОШВЫ — не ошибка, а ответ: пятна нет, и сказать надо именно это. */
  const tilted = [[[0,0,0],[10,1,0],[0,1,10]], [[0,0,0],[0,1,10],[10,1,0]]];
  const g = bedGripSpec(tilted, P({}));
  chk('деталь без плоской подошвы: пятно ноль, запас отрицателен', g.area === 0 && g.margin < 0, g);
}

