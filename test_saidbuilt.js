  /* СБОР — ОТДЕЛЬНОЙ ФУНКЦИЕЙ, и подложенный исходник идёт через НЕЁ ЖЕ (v25.43.0). Прежде проба
     повторяла оба прохода у себя, и мутация «снять счёт копий внутри функции» её пережила: проба
     считала своё, а перепись — своё. Теперь машинка одна. */
