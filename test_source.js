// Гигиена самого исходника — то немногое, что нельзя спросить у собранного бандла.
//
// Зачем это существует. Приложение живёт в одном файле, и объявлений функций верхнего уровня в нём
// под шесть сотен, все в одной области видимости. Объявить вторую функцию с уже занятым именем — не
// ошибка для JavaScript: побеждает последнее объявление, и все вызовы первой молча уходят в чужое
// тело. Если сигнатуры при этом отличаются, получается НЕ падение, а правдоподобный результат:
// аргументы садятся не в те слоты, деталь строится, габариты выглядят разумно, и разницу видно
// только по косвенным следам — например, по тому, что сетка перестала замыкаться, а координата,
// которой полагалось лежать в пределах четырёх миллиметров, доходит до двадцати пяти.
//
// Собранный бандл этого показать не может: там от двух объявлений остаётся одно имя, и обе стороны
// коллизии выглядят как одна функция. Поэтому файл читается с диска.
//
// Проверка стоит два сравнения и закрывает целый класс ошибок, который иначе виден только по
// симптомам. Запускать через ./run-all.sh.
const fs = require('fs');

let pass = 0, fail = 0;
function chk(n, c, e){ if(c){ pass++; console.log('  OK  ', n); } else { fail++; console.log('  FAIL', n, e !== undefined ? JSON.stringify(e) : ''); } }

const src = fs.readFileSync('parametric-stl-generator.html', 'utf8');
const lines = src.split('\n');
/* Второй <script> — это код приложения; первый несёт встроенную Three.js, и её мы не судим: она
   чужая, минифицированная и объявлений верхнего уровня в привычном виде не содержит. */
let inApp = false, seen = 0;
const decl = new Map();
for (let i = 0; i < lines.length; i++){
  const L = lines[i];
  if (/<script>/.test(L)){ seen++; inApp = seen >= 2; continue; }
  if (/<\/script>/.test(L)){ inApp = false; continue; }
  if (!inApp) continue;
  const m = /^function\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*\(/.exec(L);
  if (m){ if (!decl.has(m[1])) decl.set(m[1], []); decl.get(m[1]).push(i + 1); }
}

console.log('=== в коде приложения нет двух функций с одним именем ===');
/* Нижняя граница здесь не украшение: если разбор сломается (поменяется разметка, съедет <script>),
   карта окажется пустой, и проверка на дубли пройдёт триумфально, ничего не проверив. */
chk('объявления вообще нашлись', decl.size > 400, decl.size);
const dups = [...decl.entries()].filter(([, ls]) => ls.length > 1);
chk('ни одно имя не объявлено дважды', dups.length === 0,
    dups.map(([n, ls]) => n + ' @ строки ' + ls.join(', ')));

console.log('\n=== README не врёт про размер файла ===');
/* РАЗМЕР — ЕДИНСТВЕННОЕ ЧИСЛО README, КОТОРОЕ РАСТЁТ САМО, и молча: в README стояло «~2.0 МБ» при
   3.5 МБ на диске, и ещё дважды тот же файл назван «2.5 МБ» в разделе про PWA — там на нём держится
   целое рассуждение о секундах заставки по мобильной сети. Проверять такое на глаз нельзя, поэтому
   сверяется со СТАТОМ файла.
   ОГОВОРКА, которую надо помнить, если README пополнится: под правило попадают ВСЕ числа «N МБ» в
   README — сегодня их три, и все три про этот файл. Появится размер чего-то другого — проверку
   придётся научить их различать, а не ослаблять допуск. */
{
  const readme = fs.readFileSync('README.md', 'utf8');
  const real = fs.statSync('parametric-stl-generator.html').size / (1024*1024);
  const said = [...readme.matchAll(/([\d]+[.,]?[\d]*)\s*МБ/g)].map(m => parseFloat(m[1].replace(',', '.')));
  chk('размер в README назван', said.length >= 1, said);
  const off = said.map(v => Math.abs(v - real) / real);
  chk('и он сходится с файлом (' + real.toFixed(2) + ' МБ, названо ' + said.join(', ') + ')',
      off.every(d => d <= 0.10), said.filter((v, i) => off[i] > 0.10));
}

console.log('\n=== TOTAL: ' + pass + ' passed, ' + fail + ' failed ===');
process.exit(fail ? 1 : 0);
