// Объём тела, а не сумма оболочек.
//
// `meshVolume` считает по теореме о дивергенции, и это в точности ∫w dV, где w — число оборотов. Для
// ОДНОЙ замкнутой оболочки w равно единице внутри и нулю снаружи, и ответ точен до последнего знака.
// Но половина деталей здесь собрана из ПЕРЕКРЫВАЮЩИХСЯ оболочек — две части, сошедшиеся по одной
// плоскости, объединением не становятся, — и в перекрытии w равно двум. Тело занимает область w ≥ 1,
// значит `meshVolume` завышает его ровно на ∫(w−1)⁺dV.
//
// Проверяется здесь то, на чём я дважды ошибся, пока это искал:
//
//   1. У ОДНОСКОРЛУПНОЙ ДЕТАЛИ ПОПРАВКА РОВНО НОЛЬ, и точный ответ обязан остаться точным ДО
//      ПОСЛЕДНЕГО ЗНАКА. Считать объём колоннами заново было бы проще, но у колонной выборки
//      систематический недобор на кривых силуэтах: крест мальтийского, деталь односкорлупная, «терял»
//      так полтора процента, и первая редакция переписи обвинила его в перекрытии.
//
//   2. ЛУЧ, ИДУЩИЙ ПО ДИАГОНАЛИ ГРАНИ, ПОДДЕЛЫВАЕТ ПЕРЕКРЫТИЕ. Он протыкает оба треугольника нижней
//      грани на одной высоте и с одним знаком, и число оборотов подскакивает до двух там, где ничего
//      не перекрывается: обычный куб 40³ получал «лишних 640 мм³» — ровно сорок миллиметров на те сто
//      клеток, через которые проходит диагональ сетки 100×100.
//
//   3. ЗАМЕРУ ПРОЛЁТА тот же артефакт не страшен: он спрашивает «w ≥ 1 или нет», а ложное удвоение
//      симметрично и порога не сдвигает. Разницу между двумя мерами тут и закрепляем, чтобы её не
//      «упростили» обратно.

